// Builds js/names.js: official English and Spanish names for moves, abilities, places, types and so on,
// from PokeAPI. The site uses this file instead of asking PokeAPI for each name while you browse.
//
// Run it again to pick up names PokeAPI adds later (needs Node.js 18 or newer):
//   node tools/build-names.js
//
// Pokémon species names are not included: the Spanish games use the same names as the English ones.

const fs = require('fs');
const path = require('path');

const ENDPOINT = 'https://beta.pokeapi.co/graphql/v1beta';

// What to fetch for each language: alias → [names table, the table of the thing it names]
const TABLES = {
  en: {
    moves: ['pokemon_v2_movename', 'pokemon_v2_move'],
    abilities: ['pokemon_v2_abilityname', 'pokemon_v2_ability'],
  },
  es: {
    moves: ['pokemon_v2_movename', 'pokemon_v2_move'],
    abilities: ['pokemon_v2_abilityname', 'pokemon_v2_ability'],
    locations: ['pokemon_v2_locationname', 'pokemon_v2_location'],
    types: ['pokemon_v2_typename', 'pokemon_v2_type'],
    eggGroups: ['pokemon_v2_egggroupname', 'pokemon_v2_egggroup'],
  },
};

async function query(lang, tables) {
  const fields = Object.entries(tables).map(([alias, [table, parent]]) =>
    `${alias}: ${table}(where: {pokemon_v2_language: {name: {_eq: "${lang}"}}}) { name ${parent} { name } }`);
  const res = await fetch(ENDPOINT, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ query: `{ ${fields.join(' ')} }` }),
  });
  if (!res.ok) throw new Error(`PokeAPI answered HTTP ${res.status}`);
  const { data, errors } = await res.json();
  if (errors) throw new Error(JSON.stringify(errors));

  const out = {};
  for (const [alias, [, parent]] of Object.entries(tables)) {
    const entries = data[alias]
      .filter(row => row[parent] && row.name)
      .map(row => [row[parent].name, row.name.trim()])
      .sort(([a], [b]) => a.localeCompare(b));
    out[alias] = Object.fromEntries(entries);
    console.log(`${lang}.${alias}: ${entries.length}`);
  }
  return out;
}

async function main() {
  const names = {};
  for (const [lang, tables] of Object.entries(TABLES)) names[lang] = await query(lang, tables);

  const file = path.join(__dirname, '..', 'js', 'names.js');
  fs.writeFileSync(file,
    '// Generated by tools/build-names.js from PokeAPI. Do not edit by hand: run the script again instead.\n' +
    `const NAMES = ${JSON.stringify(names)};\n`);
  console.log(`Wrote ${path.relative(process.cwd(), file)} (${fs.statSync(file).size} bytes)`);
}

main().catch(err => { console.error(err.message); process.exit(1); });
